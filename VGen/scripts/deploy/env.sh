#!/usr/bin/env bash

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEFAULT_VGEN_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
DEFAULT_WORKSPACE_ROOT="$(cd "$DEFAULT_VGEN_ROOT/.." && pwd)"
DEFAULT_DEV_ROOT="$(cd "$DEFAULT_WORKSPACE_ROOT/.." && pwd)"

VGEN_ROOT="${VGEN_ROOT:-$DEFAULT_VGEN_ROOT}"
DEV_ROOT="${DEV_ROOT:-$DEFAULT_DEV_ROOT}"
CONDA_ROOT="${CONDA_ROOT:-$DEV_ROOT/miniconda3}"
CONDA_SH="${CONDA_SH:-$CONDA_ROOT/etc/profile.d/conda.sh}"
DIFFSYNTH_ROOT="${DIFFSYNTH_ROOT:-$VGEN_ROOT/third_party/DiffSynth-Studio}"
if [[ -z "${MODELS_ROOT:-}" ]]; then
  if [[ -d "$DEV_ROOT/Models" ]]; then
    MODELS_ROOT="$DEV_ROOT/Models"
  elif [[ -d "$DEFAULT_WORKSPACE_ROOT/Models" ]]; then
    MODELS_ROOT="$DEFAULT_WORKSPACE_ROOT/Models"
  else
    MODELS_ROOT="$DEFAULT_WORKSPACE_ROOT/models"
  fi
fi

DIFF_ENV="${DIFF_ENV:-diff}"

QWEN_IMAGE_MODEL="${QWEN_IMAGE_MODEL:-$MODELS_ROOT/Qwen-Image}"
COSYVOICE_MODEL="${COSYVOICE_MODEL:-$MODELS_ROOT/CosyVoice3-0.5B-2512}"
WAN_VACE_MODEL="${WAN_VACE_MODEL:-$MODELS_ROOT/Wan2.2-VACE-Fun-A14B}"
WAN_I2V_MODEL="${WAN_I2V_MODEL:-$MODELS_ROOT/Wan2.2-I2V-A14B}"
QWEN35_27B_MODEL="${QWEN35_27B_MODEL:-$MODELS_ROOT/qwen3.5-27b}"

LOG_DIR="${LOG_DIR:-$VGEN_ROOT/logs}"
RUNTIME_DIR="${RUNTIME_DIR:-$VGEN_ROOT/runtime}"

export VGEN_ROOT DEV_ROOT CONDA_ROOT CONDA_SH DIFFSYNTH_ROOT MODELS_ROOT
export DIFF_ENV
export QWEN_IMAGE_MODEL COSYVOICE_MODEL WAN_VACE_MODEL WAN_I2V_MODEL QWEN35_27B_MODEL
export LOG_DIR RUNTIME_DIR
